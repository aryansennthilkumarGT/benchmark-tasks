def helix(radius,pitch,start,turns,color,internal=False):
    # Each tangent box is a real collider; no kinematic thread shortcut.
    shapes=[];segments=48
    for i in range(turns*segments):
        t=2*math.pi*(i+.5)/segments
        z=start+pitch*t/(2*math.pi)
        shapes.append(box((radius*math.cos(t),radius*math.sin(t),z),
                          (.0015,2*math.pi*radius/segments*1.10,.0012),color,quat((0,0,1),t)))
    return shapes


