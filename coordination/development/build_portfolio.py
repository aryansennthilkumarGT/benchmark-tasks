def dump(path, obj):
    path.write_text(json.dumps(obj, indent=2, allow_nan=False)+'\n', encoding='utf-8')


def quat(axis, radians):
    return [math.sin(radians/2)*v for v in axis]+[math.cos(radians/2)]


def rotate(q, p):
    x,y,z,w=q
    return [(1-2*y*y-2*z*z)*p[0]+(2*x*y-2*z*w)*p[1]+(2*x*z+2*y*w)*p[2],
            (2*x*y+2*z*w)*p[0]+(1-2*x*x-2*z*z)*p[1]+(2*y*z-2*x*w)*p[2],
            (2*x*z-2*y*w)*p[0]+(2*y*z+2*x*w)*p[1]+(1-2*x*x-2*y*y)*p[2]]


def box(pos, size, color=GREY, q=Q, collision=True):
    return dict(kind='box', pos=list(pos), size=list(size), quat=list(q), color=list(color), collision=collision)


def cyl(pos, radius, height, color=GREY, q=Q, collision=True):
    return dict(kind='cylinder', pos=list(pos), radius=radius, height=height, quat=list(q), color=list(color), collision=collision)


def body(name, pos, shapes, mass=0.1, anchor=False, q=Q, material='rigid engineering plastic'):
    half=[0.,0.,0.]
    lo=[math.inf]*3;hi=[-math.inf]*3
    for s in shapes:
        if not s.get('collision',True): continue
        h=[v/2 for v in s['size']] if s['kind']=='box' else [s['radius'],s['radius'],s['height']/2]
        for sx in (-1,1):
            for sy in (-1,1):
                for sz in (-1,1):
                    v=rotate(s['quat'],[sx*h[0],sy*h[1],sz*h[2]])
                    half=[max(half[i],abs(s['pos'][i]+v[i])) for i in range(3)]
                    lo=[min(lo[i],s['pos'][i]+v[i]) for i in range(3)]
                    hi=[max(hi[i],s['pos'][i]+v[i]) for i in range(3)]
    return dict(name=name,pos=list(pos),quat=list(q),shapes=shapes,mass=mass,anchor=anchor,
                half_extent=half,bounds_min=lo,bounds_max=hi,material=material)


def assembly(b, others=(), joints=()):
    return dict(name=b['name']+'_asset',origin=list(b['pos']),fixed=b['anchor'],bodies=[b,*others],joints=list(joints))


def joint(name,parent,child,axis,lower,upper,p0,p1,kind='prismatic',stiffness=0.,damping=0.02):
    return dict(name=name,parent=parent,child=child,axis=axis,lower=lower,upper=upper,
                pivot_parent=list(p0),pivot_child=list(p1),kind=kind,stiffness=stiffness,damping=damping)


def pose(name, pos, reference=None, q=Q, tol=.003, degrees=6):
    return dict(kind='pose',body=name,pos=list(pos),relative_to=reference,quat=list(q),tolerance=tol,angle=math.radians(degrees))


def jrange(name,lo,hi): return dict(kind='joint',joint=name,min=lo,max=hi)
def still(name): return dict(kind='still',body=name,speed=.01,spin=.2)
def region(name,lo,hi): return dict(kind='region',body=name,min=list(lo),max=list(hi))
def goal(name, predicates, weight=1.): return dict(name=name,all=predicates,weight=weight)


def scene(slug,title,instruction,context,limit=3600):
    return dict(slug=slug,title=title,instruction=instruction,context=context,control_hz=20,
                run_limit=limit,table_top=TOP,hold_seconds=1.,penetration_limit=.002,
                assemblies=[],goals=[],threads=[],invariants=[],collision_exclusions=[],
                novelty_status='HOLD_NOT_CLEARED',implementation_status='ENGINEERING_DRAFT_UNVALIDATED',
                limitations=[],closest_prs=[],expert_operations=[])


def add(s,b,others=(),joints=()):
    s['assemblies'].append(assembly(b,others,joints));return b


def tray(s,name,xy,size=(.14,.10),color=GREY):
    x,y=size
    shapes=[box((0,0,.003),(x,y,.006),color),box((0,y/2,.02),(x,.004,.04),color),
            box((0,-y/2,.02),(x,.004,.04),color),box((x/2,0,.02),(.004,y,.04),color),
            box((-x/2,0,.02),(.004,y,.04),color)]
    add(s,body(name,(*xy,TOP),shapes,mass=.5,anchor=True))
    return ([xy[0]-x/2+.003,xy[1]-y/2+.003,TOP+.006],
            [xy[0]+x/2-.003,xy[1]+y/2-.003,TOP+.09])


def pick(s,name,target,side=None,yaw=0.,place_yaw=0.):
    bs=next(b for a in s['assemblies'] for b in a['bodies'] if b['name']==name)
    side=side or ('left' if bs['pos'][1]>=0 else 'right')
    # Draft top grasp; no claim of contact or reachability follows from these waypoints.
    s['expert_operations'].append(dict(kind='transfer',body=name,side=side,pick=bs['pos'],place=list(target),
                                       yaw=yaw,place_yaw=place_yaw,grasp_offset=.008))


