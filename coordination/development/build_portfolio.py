def expert_plan(s):
    arms={'left':[],'right':[]}
    homes={'left':[.24,.25,TOP+.15],'right':[.24,-.25,TOP+.15]}
    t=0.
    def append(side,duration,pos,opened,label,yaw=0):
        arms[side].append(dict(duration=duration,pos=list(pos),open=opened,label=label,yaw=yaw))
    for op in s['expert_operations']:
        side=op['side'];other='right' if side=='left' else 'left'
        start=[*op['pick']];end=[*op['place']]
        start[2]+=op['grasp_offset'];end[2]+=op['grasp_offset']
        steps=[(1.5,[start[0],start[1],TOP+.15],True,'approach'),(1.5,start,True,'descend'),
               (.8,start,False,'grasp'),(1.3,[start[0],start[1],TOP+.15],False,'lift'),
               (2.,[end[0],end[1],TOP+.15],False,'transfer'),(1.5,end,False,'seat'),
               (.8,end,True,'release'),(1.5,homes[side],True,'retreat')]
        for duration,pos,opened,label in steps:append(side,duration,pos,opened,op['body']+': '+label,op['yaw'] if label in ('approach','descend','grasp','lift') else op['place_yaw'])
        append(other,sum(x[0] for x in steps),homes[other],True,'wait for '+op['body'])
        t+=sum(x[0] for x in steps)
    for side in arms:append(side,2.,homes[side],True,'final release hold')
    return dict(status='EXECUTABLE_DRAFT_UNVALIDATED',kind='ROBOT_WAYPOINTS_NOT_EVIDENCE',
                limitations='Nominal top grasps only. Access-opening, latch actuation, threading, handoffs and collision avoidance require task-specific controller completion on the actual robot.',
                planned_seconds=t+2,arms=arms)


